# Prometheus Counters
LLM_USAGE_INPUT = Counter("llm_usage_input", "Total input tokens sent to LLM", ["model", "chat", "function"])
LLM_USAGE_INPUT_CACHE_HIT = Counter("llm_usage_input_cache_hit", "Input tokens served from prompt cache", ["model", "chat", "function"])
LLM_USAGE_INPUT_CACHE_MISS = Counter("llm_usage_input_cache_miss", "Input tokens that missed prompt cache", ["model", "chat", "function"])
LLM_USAGE_OUTPUT = Counter("llm_usage_output", "Total output tokens generated by LLM", ["model", "chat", "function"])

# Real-time log buffer (stores last 500 logs in memory)
MAX_LOGS = 500
log_buffer = deque(maxlen=MAX_LOGS)
log_subscribers = set()
_web_loop = None

def _broadcast_entry(entry: dict):
    dead_subscribers = set()
    for queue in list(log_subscribers):
        try:
            queue.put_nowait(entry)
        except Exception:
            dead_subscribers.add(queue)
    for dead in dead_subscribers:
        log_subscribers.discard(dead)

def log_event(category: str, text: str):
    """
    Logs an event to console and broadcasts to real-time web UI dashboard.
    """
    now_str = datetime.now().strftime("%H:%M:%S")
    entry = {
        "id": int(time.time() * 1000),
        "time": now_str,
        "category": category,
        "text": text
    }
    log_buffer.append(entry)
    print(f"[{now_str}] [{category}] {text}")

    # Broadcast thread-safely to web event loop
    global _web_loop
    if _web_loop and _web_loop.is_running():
        _web_loop.call_soon_threadsafe(_broadcast_entry, entry)

def track_llm_usage(model: str, input_tokens: int, output_tokens: int, cache_hit: int = 0, chat: str = "general", function: str = "chat"):
    model = model or "unknown"
    chat = chat or "general"
    function = function or "chat"
    cache_miss = max(0, input_tokens - cache_hit)
    
    LLM_USAGE_INPUT.labels(model=model, chat=chat, function=function).inc(input_tokens)
    LLM_USAGE_OUTPUT.labels(model=model, chat=chat, function=function).inc(output_tokens)
    if cache_hit > 0:
        LLM_USAGE_INPUT_CACHE_HIT.labels(model=model, chat=chat, function=function).inc(cache_hit)
    if cache_miss > 0:
        LLM_USAGE_INPUT_CACHE_MISS.labels(model=model, chat=chat, function=function).inc(cache_miss)

    log_event("METRICS", f"[{function}] Model: {model} | In: {input_tokens} tokens | Out: {output_tokens} tokens")

