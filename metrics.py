async def handle_index(request):
    return web.Response(text=LOGS_HTML, content_type='text/html')

async def handle_metrics(request):
    data = generate_latest()
    return web.Response(body=data, content_type="text/plain")

async def handle_logs_history(request):
    return web.json_response(list(log_buffer))

async def handle_logs_stream(request):
    response = web.StreamResponse(
        status=200,
        reason='OK',
        headers={
            'Content-Type': 'text/event-stream',
            'Cache-Control': 'no-cache',
            'Connection': 'keep-alive',
        }
    )
    await response.prepare(request)

    queue = asyncio.Queue()
    log_subscribers.add(queue)

    try:
        while True:
            log_entry = await queue.get()
            data_str = f"data: {json.dumps(log_entry)}\n\n"
            await response.write(data_str.encode('utf-8'))
    except (asyncio.CancelledError, ConnectionResetError):
        pass
    finally:
        log_subscribers.discard(queue)

    return response

_server_started = False

def start_metrics_server():
    global _server_started
    if _server_started:
        return
    _server_started = True

    port = config_instance.get("general", "metrics_port", 9464)

    async def _run_app():
        global _web_loop
        _web_loop = asyncio.get_running_loop()

        app = web.Application()
        app.router.add_get('/', handle_index)
        app.router.add_get('/logs', handle_index)
        app.router.add_get('/metrics', handle_metrics)
        app.router.add_get('/api/logs/history', handle_logs_history)
        app.router.add_get('/stream/logs', handle_logs_stream)

        runner = web.AppRunner(app)
        await runner.setup()
        site = web.TCPSite(runner, '0.0.0.0', port)
        await site.start()
        print(f"[Metrics] Dashboard & Real-Time Logs Web Server running at http://localhost:{port}/")

    def _start_thread():
        loop = asyncio.new_event_loop()
        asyncio.set_event_loop(loop)
        loop.run_until_complete(_run_app())
        loop.run_forever()

    t = threading.Thread(target=_start_thread, daemon=True)
    t.start()
